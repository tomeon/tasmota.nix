#!/usr/bin/env python3
"""Deploy declarative Tasmota device configurations with decode-config.

The manifest (JSON, normally generated by the tasmota.nix module) lists the
devices and their settings.  Settings are partial decode-config JSON: only
the keys you declare are written; everything else on the device is kept.

Commands:
  build   validate settings offline against a blank configuration dump
  diff    show what `switch` would change on each device
  switch  apply settings to devices whose configuration differs
  pull    print each device's current configuration as JSON

A device reboots after its configuration is uploaded, so `switch` only
uploads to devices whose configuration would actually change.
"""

import argparse
import concurrent.futures
import dataclasses
import datetime
import json
import os
import shutil
import subprocess
import sys
import tempfile
import threading

MANIFEST_VERSION = 1
SECRET_KEY = "_secret"
# Stand-in for secret values when validating offline; secrets are not read.
PLACEHOLDER_SECRET = "x"
# Checksums change with any other setting; showing them in diffs is noise.
DIFF_IGNORED_KEYS = frozenset({"cfg_crc", "cfg_crc32"})
# How decode-config renders every password field with --json-hide-pw.
HIDDEN_PASSWORD = "********"


class DeployError(Exception):
    pass


@dataclasses.dataclass
class Device:
    name: str
    source: str
    password_file: str | None = None
    tags: list[str] = dataclasses.field(default_factory=list)
    settings: dict = dataclasses.field(default_factory=dict)
    extra_args: list[str] = dataclasses.field(default_factory=list)
    validate: bool = True


@dataclasses.dataclass
class Manifest:
    decode_config: str
    blank_dump: str | None
    devices: dict[str, Device]


def load_manifest(path):
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as err:
        raise DeployError(f"cannot read manifest {path}: {err}") from err
    if data.get("version") != MANIFEST_VERSION:
        raise DeployError(
            f"manifest {path} has version {data.get('version')!r}, "
            f"expected {MANIFEST_VERSION}"
        )
    devices = {
        name: Device(
            name=name,
            source=d["source"],
            password_file=d.get("passwordFile"),
            tags=d.get("tags", []),
            settings=d.get("settings", {}),
            extra_args=d.get("extraArgs", []),
            validate=d.get("validate", True),
        )
        for name, d in data.get("devices", {}).items()
    }
    return Manifest(
        decode_config=data["decodeConfig"],
        blank_dump=data.get("blankDump"),
        devices=devices,
    )


def select_devices(devices, selector):
    """Select devices by a comma-separated list of names and @tags."""
    if not selector:
        return [devices[name] for name in sorted(devices)]
    chosen = set()
    for item in (s.strip() for s in selector.split(",")):
        if not item:
            continue
        if item.startswith("@"):
            tag = item[1:]
            matches = {n for n, d in devices.items() if tag in d.tags}
            if not matches:
                raise DeployError(f"no device has tag {tag!r}")
            chosen |= matches
        elif item in devices:
            chosen.add(item)
        else:
            raise DeployError(f"unknown device {item!r}")
    if not chosen:
        raise DeployError("no devices selected")
    return [devices[name] for name in sorted(chosen)]


def read_secret(path):
    """Read a secret file, dropping trailing newlines like `$(<file)`."""
    try:
        with open(path, encoding="utf-8") as f:
            return f.read().rstrip("\n")
    except OSError as err:
        raise DeployError(f"cannot read secret {path}: {err}") from err


def is_secret_ref(value):
    return isinstance(value, dict) and set(value) == {SECRET_KEY}


def resolve_secrets(value, read):
    """Replace every `{"_secret": path}` in `value` with `read(path)`."""
    if is_secret_ref(value):
        return read(value[SECRET_KEY])
    if isinstance(value, dict):
        return {k: resolve_secrets(v, read) for k, v in value.items()}
    if isinstance(value, list):
        return [resolve_secrets(v, read) for v in value]
    return value


def diff_values(before, after, path=""):
    """Yield (path, before, after) for each leaf that differs."""
    if isinstance(before, dict) and isinstance(after, dict):
        for key in sorted(set(before) | set(after)):
            if not path and key in DIFF_IGNORED_KEYS:
                continue
            sub = f"{path}.{key}" if path else key
            yield from diff_values(before.get(key), after.get(key), sub)
    elif (
        isinstance(before, list)
        and isinstance(after, list)
        and len(before) == len(after)
    ):
        for i, (b, a) in enumerate(zip(before, after)):
            yield from diff_values(b, a, f"{path}[{i}]")
    elif before != after:
        yield path, before, after


def leaves(value, path=""):
    """Yield (path, value) for each leaf, with paths as in diff_values."""
    if isinstance(value, dict):
        for key in sorted(value):
            yield from leaves(value[key], f"{path}.{key}" if path else key)
    elif isinstance(value, list):
        for i, v in enumerate(value):
            yield from leaves(v, f"{path}[{i}]")
    else:
        yield path, value


def format_changes(changes, hidden=frozenset()):
    """Format changes; values at `hidden` paths are not shown."""
    return [
        f"  {path}: changed (hidden)"
        if path in hidden
        else f"  {path}: {json.dumps(b, ensure_ascii=False)} -> "
        f"{json.dumps(a, ensure_ascii=False)}"
        for path, b, a in changes
    ]


def write_private(path, text):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)


def password_config(password):
    """Render a decode-config (configargparse) config file setting the password.

    Passing the password in a file keeps it out of the process list.  Quoting
    preserves spaces, quotes, `#` and `;`; configargparse would still parse a
    value shaped like `[...]` as a list, and a file cannot hold a newline.
    """
    if "\n" in password or "\r" in password:
        raise DeployError("password contains a newline")
    if password.startswith("[") and password.endswith("]"):
        raise DeployError(
            "password of the form [...] cannot be passed to decode-config"
        )
    return f'password = "{password}"\n'


class DecodeConfig:
    """Runs decode-config for one device inside a private working directory."""

    def __init__(self, exe, device, workdir, timeout):
        self.exe = exe
        self.device = device
        self.workdir = workdir
        self.timeout = timeout
        self._config = None

    def _remote_args(self):
        args = ["--source", self.device.source]
        if self.device.password_file:
            if self._config is None:
                self._config = os.path.join(self.workdir, "decode-config.conf")
                password = read_secret(self.device.password_file)
                write_private(self._config, password_config(password))
            args += ["--config", self._config]
        return args

    def run(self, *args):
        cmd = [self.exe, *args, *self.device.extra_args]
        try:
            proc = subprocess.run(
                cmd,
                stdin=subprocess.DEVNULL,
                capture_output=True,
                text=True,
                timeout=self.timeout,
                cwd=self.workdir,
                check=False,
            )
        except subprocess.TimeoutExpired as err:
            raise DeployError(f"decode-config timed out after {self.timeout}s") from err
        except OSError as err:
            raise DeployError(f"cannot run decode-config: {err}") from err
        if proc.returncode != 0:
            detail = (proc.stderr or proc.stdout).strip()
            raise DeployError(
                f"decode-config exited with status {proc.returncode}"
                + (":\n" + _indent(detail) if detail else "")
            )
        return proc.stdout

    def pull(self, dump):
        self.run(
            *self._remote_args(),
            "--backup-file",
            dump,
            "--backup-type",
            "dmp",
            "--no-extension",
        )

    def push(self, settings_file):
        self.run(
            *self._remote_args(),
            "--restore-file",
            settings_file,
            "--no-extension",
            "--force-restore",
        )

    def decode(self, source_args, show_passwords=False):
        pw = "--json-show-pw" if show_passwords else "--json-hide-pw"
        out = self.run(*source_args, "--output-format", "json", pw)
        try:
            config = json.loads(out)
        except ValueError as err:
            raise DeployError(f"decode-config printed invalid JSON: {err}") from err
        config.pop("header", None)
        return config

    def decode_remote(self):
        return self.decode(self._remote_args())

    def decode_file(self, dump, show_passwords=False):
        return self.decode(["--source", dump], show_passwords)

    def apply_file(self, dump, settings_file):
        self.run(
            "--source",
            dump,
            "--restore-file",
            settings_file,
            "--no-extension",
            "--force-restore",
        )


def _indent(text, prefix="    "):
    return "\n".join(prefix + line for line in text.splitlines())


@dataclasses.dataclass
class Plan:
    changed: bool
    changes: list
    hidden: frozenset
    settings_file: str


def plan(dc, device, current, read):
    """Apply the device's settings to a copy of `current` and compare.

    Errors in the settings (unknown keys, invalid values) surface here,
    before anything is written to the device.
    """
    before = dc.decode_file(current, show_passwords=True)
    desired = resolve_secrets(device.settings, read)
    # decode-config assumes ESP8266 for restore JSON without config_version
    # and rejects it on other platforms, so copy the device's value.
    if "config_version" in before:
        desired["config_version"] = before["config_version"]
    settings_file = os.path.join(dc.workdir, "settings.json")
    write_private(settings_file, json.dumps(desired))

    proposed = os.path.join(dc.workdir, "proposed.dmp")
    shutil.copyfile(current, proposed)
    dc.apply_file(proposed, settings_file)
    with open(current, "rb") as a, open(proposed, "rb") as b:
        changed = a.read() != b.read()
    if not changed:
        return Plan(False, [], frozenset(), settings_file)
    # Diff with real values, but remember which paths are passwords so
    # their values are never printed.
    after = dc.decode_file(proposed, show_passwords=True)
    hidden = frozenset(
        path
        for path, value in leaves(dc.decode_file(current))
        if value == HIDDEN_PASSWORD
    )
    return Plan(True, list(diff_values(before, after)), hidden, settings_file)


def describe(plan_):
    if not plan_.changed:
        return ["up to date"]
    if not plan_.changes:
        return ["changes not visible in decoded settings"]
    n = len(plan_.changes)
    return [
        f"{n} change{'s' if n != 1 else ''}",
        *format_changes(plan_.changes, plan_.hidden),
    ]


def do_build(manifest, device, dc, args):
    if not device.validate:
        return "skip", ["validation disabled"]
    if not manifest.blank_dump:
        raise DeployError("manifest has no blankDump to validate against")
    current = os.path.join(dc.workdir, "blank.dmp")
    shutil.copyfile(manifest.blank_dump, current)
    os.chmod(current, 0o600)
    plan(dc, device, current, lambda _path: PLACEHOLDER_SECRET)
    return "ok", ["settings valid"]


def do_diff(manifest, device, dc, args):
    current = os.path.join(dc.workdir, "current.dmp")
    dc.pull(current)
    p = plan(dc, device, current, read_secret)
    return ("changed" if p.changed else "ok"), describe(p)


def do_switch(manifest, device, dc, args):
    current = os.path.join(dc.workdir, "current.dmp")
    dc.pull(current)
    p = plan(dc, device, current, read_secret)
    lines = describe(p)
    if not p.changed:
        return "ok", lines
    if args.backup_dir:
        stamp = datetime.datetime.now(datetime.UTC).strftime("%Y%m%dT%H%M%SZ")
        backup = os.path.join(args.backup_dir, f"{device.name}-{stamp}.dmp")
        os.makedirs(args.backup_dir, exist_ok=True)
        shutil.copyfile(current, backup)
        lines.append(f"backed up previous configuration to {backup}")
    dc.push(p.settings_file)
    lines.append("applied; the device restarts")
    return "changed", lines


def do_pull(manifest, device, dc, args):
    config = dc.decode_remote()
    text = json.dumps(config, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    if args.output_dir:
        os.makedirs(args.output_dir, exist_ok=True)
        path = os.path.join(args.output_dir, f"{device.name}.json")
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        return "ok", [f"wrote {path}"]
    return "ok", config


COMMANDS = {
    "build": do_build,
    "diff": do_diff,
    "switch": do_switch,
    "pull": do_pull,
}


def run_device(manifest, device, args):
    with tempfile.TemporaryDirectory(prefix=f"tasmota-{device.name}-") as workdir:
        dc = DecodeConfig(manifest.decode_config, device, workdir, args.timeout)
        try:
            return COMMANDS[args.command](manifest, device, dc, args)
        except DeployError as err:
            return "failed", str(err).splitlines()


def parse_args(argv):
    parser = argparse.ArgumentParser(
        prog="tasmota-deploy",
        description=__doc__.split("\n\n")[0],
        epilog="\n\n".join(__doc__.split("\n\n")[1:]),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--manifest", required=True, help="device manifest (JSON)")
    sub = parser.add_subparsers(dest="command", required=True, metavar="COMMAND")

    common = argparse.ArgumentParser(add_help=False)
    common.add_argument(
        "--on",
        metavar="SELECTOR",
        help="comma-separated device names and @tags (default: all devices)",
    )
    common.add_argument(
        "-j", "--jobs", type=int, default=4, help="devices to process in parallel"
    )
    common.add_argument(
        "--timeout",
        type=float,
        default=120,
        help="seconds to allow each decode-config run (default: 120)",
    )

    sub.add_parser("build", parents=[common], help="validate settings offline")
    sub.add_parser("diff", parents=[common], help="show pending changes")
    switch = sub.add_parser("switch", parents=[common], help="apply settings")
    switch.add_argument(
        "--backup-dir",
        metavar="DIR",
        help="save each device's previous configuration (.dmp) here before changing it",
    )
    pull = sub.add_parser("pull", parents=[common], help="print current configuration")
    pull.add_argument(
        "-o", "--output-dir", metavar="DIR", help="write DIR/<device>.json files"
    )
    args = parser.parse_args(argv)
    if args.jobs < 1:
        parser.error("--jobs must be at least 1")
    return args


def main(argv=None):
    args = parse_args(argv)
    try:
        manifest = load_manifest(args.manifest)
        devices = select_devices(manifest.devices, args.on)
    except DeployError as err:
        print(f"tasmota-deploy: {err}", file=sys.stderr)
        return 2

    results = {}
    lock = threading.Lock()

    def report(device, status, lines):
        results[device.name] = status
        if isinstance(lines, dict):  # pull without --output-dir
            return
        with lock:
            stream = sys.stderr if status == "failed" else sys.stdout
            head, *rest = lines
            print(
                f"{device.name}: {status}: {head}"
                if status == "failed"
                else f"{device.name}: {head}",
                file=stream,
            )
            for line in rest:
                print(line if line.startswith(" ") else f"  {line}", file=stream)
            stream.flush()

    pulled = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = {pool.submit(run_device, manifest, d, args): d for d in devices}
        for future in concurrent.futures.as_completed(futures):
            device = futures[future]
            status, lines = future.result()
            if isinstance(lines, dict):
                pulled[device.name] = lines
            report(device, status, lines)

    if pulled:
        json.dump(pulled, sys.stdout, indent=2, sort_keys=True, ensure_ascii=False)
        sys.stdout.write("\n")

    failed = sorted(n for n, s in results.items() if s == "failed")
    if args.command in ("diff", "switch") or failed:
        changed = sum(1 for s in results.values() if s == "changed")
        verb = "would change" if args.command == "diff" else "changed"
        print(
            f"{len(results)} device(s): {changed} {verb}, {len(failed)} failed"
            + (f" ({', '.join(failed)})" if failed else ""),
            file=sys.stderr,
        )
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
