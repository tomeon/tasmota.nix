"""End-to-end tests: tasmota-deploy + decode-config against mock devices.

Environment:
  DECODE_CONFIG       path to decode-config.py (required)
  BLANK_DUMP_ESP82    blank ESP8266 configuration dump (required)
  BLANK_DUMP_ESP32    blank ESP32 configuration dump (required)
  KEY_SCHEMA          settings key schema over all platforms (required)
  TASMOTA_DEPLOY      tasmota-deploy executable (default: run the source)
  NIX_MANIFEST        manifest generated by the Nix module (optional)
"""

import json
import os
import shlex
import subprocess
import sys
import tempfile
import unittest

from mock_tasmota import MockTasmota

HERE = os.path.dirname(os.path.abspath(__file__))
DECODE_CONFIG = os.environ.get("DECODE_CONFIG")
DUMPS = {
    "esp82": os.environ.get("BLANK_DUMP_ESP82"),
    "esp32": os.environ.get("BLANK_DUMP_ESP32"),
}
KEY_SCHEMA = os.environ.get("KEY_SCHEMA")
DEPLOY = shlex.split(
    os.environ.get("TASMOTA_DEPLOY")
    or shlex.join([sys.executable, os.path.join(HERE, "..", "tasmota_deploy.py")])
)


def blank(kind):
    with open(DUMPS[kind], "rb") as f:
        return f.read()


@unittest.skipUnless(
    DECODE_CONFIG and all(DUMPS.values()) and KEY_SCHEMA,
    "DECODE_CONFIG/BLANK_DUMP_*/KEY_SCHEMA not set",
)
class Integration(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.tmp = tmp.name

    def path(self, name):
        return os.path.join(self.tmp, name)

    def secret(self, name, value):
        path = self.path(name)
        with open(path, "w") as f:
            f.write(value + "\n")
        return path

    def mock(self, kind="esp82", password=None):
        m = MockTasmota(blank(kind), password=password)
        m.__enter__()
        self.addCleanup(m.__exit__)
        return m

    def manifest(self, devices, **extra):
        path = self.path("manifest.json")
        with open(path, "w") as f:
            json.dump(
                {
                    "version": 1,
                    "decodeConfig": DECODE_CONFIG,
                    "blankDump": DUMPS["esp82"],
                    "keySchema": KEY_SCHEMA,
                    "devices": devices,
                    **extra,
                },
                f,
            )
        return path

    def deploy(self, manifest, *args):
        return subprocess.run(
            [*DEPLOY, "--manifest", manifest, *args],
            capture_output=True,
            text=True,
            cwd=self.tmp,
            check=False,
            # A common umask, so file permission checks mean something.
            umask=0o022,
        )

    def device_config(self, mock):
        """Decode the mock's current dump, passwords included."""
        dump = self.path("inspect.dmp")
        with open(dump, "wb") as f:
            f.write(mock.dump)
        out = subprocess.run(
            [DECODE_CONFIG, "-s", dump, "--json-show-pw"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        return json.loads(out)

    def assertOk(self, proc):
        self.assertEqual(proc.returncode, 0, proc.stdout + proc.stderr)

    def assertFailed(self, proc):
        self.assertEqual(proc.returncode, 1, proc.stdout + proc.stderr)

    # -- switch / diff -------------------------------------------------------

    def test_switch_applies_once_then_is_idempotent(self):
        esp82, esp32 = self.mock("esp82"), self.mock("esp32")
        settings = {"friendlyname": ["Kitchen"], "mqtt_host": "broker.lan"}
        m = self.manifest(
            {
                "esp82": {"source": esp82.url, "settings": settings},
                "esp32": {"source": esp32.url, "settings": settings},
            }
        )
        first = self.deploy(m, "switch")
        self.assertOk(first)
        self.assertIn('friendlyname[0]: "" -> "Kitchen"', first.stdout)
        self.assertIn('mqtt_host: "" -> "broker.lan"', first.stdout)
        self.assertIn("2 device(s): 2 changed, 0 failed", first.stderr)
        for mock in (esp82, esp32):
            self.assertEqual(mock.uploads, 1)
            config = self.device_config(mock)
            self.assertEqual(config["friendlyname"][0], "Kitchen")
            self.assertEqual(config["mqtt_host"], "broker.lan")
        self.assertEqual(self.device_config(esp32)["config_version"], 1)

        second = self.deploy(m, "switch")
        self.assertOk(second)
        self.assertIn("esp82: up to date", second.stdout)
        self.assertIn("esp32: up to date", second.stdout)
        self.assertEqual((esp82.uploads, esp32.uploads), (1, 1))

    def test_diff_does_not_write(self):
        dev = self.mock()
        m = self.manifest(
            {"lamp": {"source": dev.url, "settings": {"hostname": "lamp"}}}
        )
        proc = self.deploy(m, "diff")
        self.assertOk(proc)
        self.assertIn("lamp: 1 change", proc.stdout)
        self.assertIn('hostname: "" -> "lamp"', proc.stdout)
        self.assertIn("1 would change", proc.stderr)
        self.assertEqual(dev.uploads, 0)
        self.assertEqual(self.device_config(dev)["hostname"], "")

    def test_untouched_keys_are_preserved(self):
        dev = self.mock()
        m1 = self.manifest({"d": {"source": dev.url, "settings": {"hostname": "one"}}})
        self.assertOk(self.deploy(m1, "switch"))
        m2 = self.manifest({"d": {"source": dev.url, "settings": {"mqtt_host": "b"}}})
        self.assertOk(self.deploy(m2, "switch"))
        config = self.device_config(dev)
        self.assertEqual((config["hostname"], config["mqtt_host"]), ("one", "b"))

    def test_relative_file_source(self):
        # decode-config runs in a private working directory; a relative
        # dump-file source must still mean the file next to the caller.
        with open(self.path("dev.dmp"), "wb") as f:
            f.write(blank("esp82"))
        m = self.manifest({"d": {"source": "dev.dmp", "settings": {"hostname": "f"}}})
        self.assertOk(self.deploy(m, "switch"))
        out = subprocess.run(
            [DECODE_CONFIG, "-s", self.path("dev.dmp")],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        self.assertEqual(json.loads(out)["hostname"], "f")

    def test_selection(self):
        a, b = self.mock(), self.mock()
        m = self.manifest(
            {
                "a": {"source": a.url, "tags": ["t"], "settings": {"hostname": "a"}},
                "b": {"source": b.url, "settings": {"hostname": "b"}},
            }
        )
        self.assertOk(self.deploy(m, "switch", "--on", "@t"))
        self.assertEqual((a.uploads, b.uploads), (1, 0))

    def test_backup_dir(self):
        dev = self.mock()
        before = dev.dump
        m = self.manifest({"d": {"source": dev.url, "settings": {"hostname": "x"}}})
        backups = self.path("backups")
        self.assertOk(self.deploy(m, "switch", "--backup-dir", backups))
        (name,) = os.listdir(backups)
        self.assertTrue(name.startswith("d-") and name.endswith(".dmp"))
        backup = os.path.join(backups, name)
        with open(backup, "rb") as f:
            self.assertEqual(f.read(), before)
        # Dumps hold recoverable Wi-Fi, MQTT and web credentials.
        self.assertEqual(os.stat(backup).st_mode & 0o777, 0o600)

    def test_backup_failure_is_a_device_failure(self):
        dev = self.mock()
        m = self.manifest({"d": {"source": dev.url, "settings": {"hostname": "x"}}})
        not_a_dir = self.secret("file", "")
        proc = self.deploy(m, "switch", "--backup-dir", not_a_dir)
        self.assertFailed(proc)
        self.assertIn("d: failed:", proc.stderr)
        self.assertIn("1 failed (d)", proc.stderr)
        self.assertNotIn("Traceback", proc.stderr)
        self.assertEqual(dev.uploads, 0)

    # -- secrets and credentials ---------------------------------------------

    def test_secrets_and_password(self):
        password = 'p # "w;'
        dev = self.mock(password=password)
        m = self.manifest(
            {
                "d": {
                    "source": dev.url,
                    "passwordFile": self.secret("web", password),
                    "settings": {
                        "sta_pwd": [{"_secret": self.secret("wifi", "s3cret")}],
                        "hostname": "d",
                    },
                }
            }
        )
        proc = self.deploy(m, "switch")
        self.assertOk(proc)
        self.assertIn("sta_pwd[0]: changed (hidden)", proc.stdout)
        self.assertNotIn("s3cret", proc.stdout + proc.stderr)
        self.assertEqual(self.device_config(dev)["sta_pwd"][0], "s3cret")

        # A change to a secret alone is detected, without showing values.
        with open(self.path("wifi"), "w") as f:
            f.write("changed\n")
        proc = self.deploy(m, "diff")
        self.assertOk(proc)
        self.assertIn("d: 1 change\n  sta_pwd[0]: changed (hidden)\n", proc.stdout)
        self.assertNotIn("s3cret", proc.stdout + proc.stderr)
        self.assertNotIn('"changed"', proc.stdout)

    def test_relative_secret_paths_resolve_from_cwd(self):
        dev = self.mock()
        self.secret("wifi", "rel")
        m = self.manifest(
            {"d": {"source": dev.url, "settings": {"sta_pwd": [{"_secret": "wifi"}]}}}
        )
        self.assertOk(self.deploy(m, "switch"))
        self.assertEqual(self.device_config(dev)["sta_pwd"][0], "rel")

    def test_secret_in_non_password_field_is_hidden(self):
        dev = self.mock()
        m = self.manifest(
            {
                "d": {
                    "source": dev.url,
                    "settings": {"mqtt_user": {"_secret": self.secret("u", "s3cret")}},
                }
            }
        )
        for command in ("diff", "switch"):
            proc = self.deploy(m, command)
            self.assertOk(proc)
            self.assertIn("mqtt_user: changed (hidden)", proc.stdout)
            self.assertNotIn("s3cret", proc.stdout + proc.stderr)
        self.assertEqual(self.device_config(dev)["mqtt_user"], "s3cret")
        proc = self.deploy(m, "pull")
        self.assertOk(proc)
        self.assertNotIn("s3cret", proc.stdout)
        self.assertEqual(json.loads(proc.stdout)["d"]["mqtt_user"], "********")

    def test_secret_in_decode_config_error_is_redacted(self):
        # decode-config echoes values that overflow Tasmota's text pool.
        secret = ("S3CR3T" * 200)[:700]
        dev = self.mock(password="right")
        m = self.manifest(
            {
                "d": {
                    "source": dev.url,
                    "passwordFile": self.secret("web", "right"),
                    "settings": {"sta_pwd": [{"_secret": self.secret("wifi", secret)}]},
                }
            }
        )
        proc = self.deploy(m, "switch")
        self.assertFailed(proc)
        self.assertIn("Text pool overflow", proc.stderr)
        self.assertIn("<secret>", proc.stderr)
        self.assertNotIn("S3CR3T", proc.stdout + proc.stderr)
        self.assertEqual(dev.uploads, 0)

    def test_wrong_password_fails(self):
        dev = self.mock(password="right")
        m = self.manifest(
            {
                "d": {
                    "source": dev.url,
                    "passwordFile": self.secret("web", "wrong"),
                    "settings": {"hostname": "x"},
                }
            }
        )
        proc = self.deploy(m, "switch")
        self.assertFailed(proc)
        self.assertIn("Unauthorized", proc.stderr)
        self.assertEqual(dev.uploads, 0)

    # -- failures --------------------------------------------------------------

    def test_unknown_nested_key_fails_before_upload(self):
        # decode-config itself silently ignores unknown nested keys.
        dev = self.mock()
        settings = {"flag": {"mqtt_enabeld": 1}}
        m = self.manifest({"d": {"source": dev.url, "settings": settings}})
        for command in ("build", "switch"):
            proc = self.deploy(m, command)
            self.assertFailed(proc)
            self.assertIn("flag.mqtt_enabeld", proc.stderr)
        self.assertEqual(dev.uploads, 0)

    def test_keys_for_other_hardware(self):
        # Valid offline (some platform has the key); rejected by a device
        # whose platform lacks it, accepted by one that has it.
        esp82, esp32 = self.mock("esp82"), self.mock("esp32")
        settings = {"user_template_esp32": {"name": "T"}}
        m = self.manifest(
            {
                "esp82": {"source": esp82.url, "settings": settings},
                "esp32": {"source": esp32.url, "settings": settings},
            }
        )
        self.assertOk(self.deploy(m, "build"))
        proc = self.deploy(m, "switch")
        self.assertFailed(proc)
        self.assertIn("esp82: failed: settings not in this device", proc.stderr)
        self.assertIn("user_template_esp32", proc.stderr)
        self.assertEqual((esp82.uploads, esp32.uploads), (0, 1))
        self.assertEqual(self.device_config(esp32)["user_template_esp32"]["name"], "T")

    def test_unknown_key_fails_before_upload(self):
        dev = self.mock()
        m = self.manifest({"d": {"source": dev.url, "settings": {"no_such_key": 1}}})
        proc = self.deploy(m, "switch")
        self.assertFailed(proc)
        self.assertIn("no_such_key", proc.stderr)
        self.assertEqual(dev.uploads, 0)

    def test_unreachable_device_fails_others_continue(self):
        dev = self.mock()
        dead = self.mock()
        dead_url = dead.url
        dead.__exit__()
        m = self.manifest(
            {
                "dead": {"source": dead_url, "settings": {"hostname": "x"}},
                "live": {"source": dev.url, "settings": {"hostname": "y"}},
            }
        )
        proc = self.deploy(m, "switch")
        self.assertFailed(proc)
        self.assertIn("dead: failed", proc.stderr)
        self.assertIn("1 failed (dead)", proc.stderr)
        self.assertEqual(dev.uploads, 1)

    # -- build / pull ----------------------------------------------------------

    def test_build_validates_offline(self):
        good = {"source": "http://good.invalid", "settings": {"hostname": "x"}}
        bad = {"source": "http://bad.invalid", "settings": {"bogus": 1}}
        skipped = {**bad, "source": "http://skipped.invalid", "validate": False}
        self.assertOk(
            self.deploy(self.manifest({"good": good, "skipped": skipped}), "build")
        )
        proc = self.deploy(self.manifest({"bad": bad}), "build")
        self.assertFailed(proc)
        self.assertIn("bogus", proc.stderr)

    def test_build_does_not_read_secrets(self):
        m = self.manifest(
            {
                "d": {
                    "source": "http://unused.invalid",
                    "passwordFile": "/nonexistent/web",
                    "settings": {"sta_pwd": [{"_secret": "/nonexistent/wifi"}]},
                }
            }
        )
        self.assertOk(self.deploy(m, "build"))

    def test_pull(self):
        dev = self.mock()
        m = self.manifest({"d": {"source": dev.url}})
        proc = self.deploy(m, "pull")
        self.assertOk(proc)
        config = json.loads(proc.stdout)["d"]
        self.assertIn("hostname", config)
        self.assertNotIn("header", config)

        out = self.path("pulled")
        self.assertOk(self.deploy(m, "pull", "-o", out))
        self.assertEqual(os.listdir(out), ["d.json"])
        self.assertEqual(os.stat(os.path.join(out, "d.json")).st_mode & 0o777, 0o600)
        self.assertOk(self.deploy(m, "pull", "-o", out))  # overwrites

    # -- manifest generated by the Nix module -----------------------------------

    @unittest.skipUnless(os.environ.get("NIX_MANIFEST"), "NIX_MANIFEST not set")
    def test_nix_manifest(self):
        with open(os.environ["NIX_MANIFEST"]) as f:
            manifest = json.load(f)
        mocks = {name: self.mock() for name in manifest["devices"]}

        def local_secrets(value):
            # Point each secret at a file in the test's directory, holding
            # "<basename>-secret".
            if isinstance(value, dict) and set(value) == {"_secret"}:
                name = os.path.basename(value["_secret"])
                return {"_secret": self.secret(name, f"{name}-secret")}
            if isinstance(value, dict):
                return {k: local_secrets(v) for k, v in value.items()}
            if isinstance(value, list):
                return [local_secrets(v) for v in value]
            return value

        for name, device in manifest["devices"].items():
            device["source"] = mocks[name].url
            device["settings"] = local_secrets(device["settings"])
            if device.get("passwordFile"):
                device["passwordFile"] = self.secret("web", "web-secret")
        path = self.path("nix-manifest.json")
        with open(path, "w") as f:
            json.dump(manifest, f)

        self.assertOk(self.deploy(path, "build"))
        self.assertOk(self.deploy(path, "switch"))
        for name, device in manifest["devices"].items():
            self.assertEqual(mocks[name].uploads, 1, name)
            config = self.device_config(mocks[name])
            for key, value in device["settings"].items():
                if not isinstance(value, (list, dict)):
                    self.assertEqual(config[key], value, f"{name}.{key}")
        self.assertEqual(
            self.device_config(mocks["kitchen"])["sta_pwd"][0], "wifi-secret"
        )


if __name__ == "__main__":
    unittest.main()
